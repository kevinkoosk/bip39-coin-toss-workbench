    def _bind_scrolling(self) -> None:
        self.root.bind_all("<MouseWheel>", self._on_mousewheel)
        self.root.bind_all("<Button-4>", self._on_linux_scroll_up)
        self.root.bind_all("<Button-5>", self._on_linux_scroll_down)

    def _on_mousewheel(self, event: tk.Event) -> None:
        if event.delta:
            steps = -1 if event.delta > 0 else 1
            self.canvas.yview_scroll(steps, "units")

    def _on_linux_scroll_up(self, _event: tk.Event) -> None:
        self.canvas.yview_scroll(-1, "units")

    def _on_linux_scroll_down(self, _event: tk.Event) -> None:
        self.canvas.yview_scroll(1, "units")

    def _update_scroll_region(self, _event: tk.Event | None = None) -> None:
        self.canvas.configure(scrollregion=self.canvas.bbox("all"))

    def _resize_content(self, event: tk.Event) -> None:
        content_width = max(event.width, self.MIN_CONTENT_WIDTH)
        self.canvas.itemconfigure(self.content_window, width=content_width)
        self._update_scroll_region()

    @staticmethod
    def _normalize_round(raw: str) -> tuple[str, list[str]]:
        compact = "".join(character for character in raw if not character.isspace())
        translated: list[str] = []
        invalid: list[str] = []

        for character in compact:
            if character in "0Oo":
                translated.append("0")
            elif character in "1Xx":
                translated.append("1")
            else:
                invalid.append(character)

        return "".join(translated), invalid

    def process_inputs(self) -> None:
        errors: list[str] = []
        normalized_rounds: list[str] = []
        first_invalid_entry: ttk.Entry | None = None

        for round_number, entry in enumerate(self.entries, start=1):
            entry.configure(style="TEntry")
            raw = entry.get()
            bits, invalid = self._normalize_round(raw)
            round_errors: list[str] = []

            if not raw.strip():
                round_errors.append("is empty")
            if invalid:
                visible_invalid = ", ".join(sorted({repr(item) for item in invalid}))
                round_errors.append(f"contains invalid symbol(s): {visible_invalid}")
            if len(bits) != 16:
                round_errors.append(
                    f"contains {len(bits)} recognised outcomes; exactly 16 are required"
                )

            if round_errors:
                entry.configure(style="Invalid.TEntry")
                if first_invalid_entry is None:
                    first_invalid_entry = entry
                errors.append(f"Round {round_number}: " + "; ".join(round_errors) + ".")
            normalized_rounds.append(bits)

        if errors:
            self._clear_results()
            self.status_var.set(
                f"Input not processed: {len(errors)} round(s) require correction."
            )
            shown_errors = errors[:10]
            if len(errors) > 10:
                shown_errors.append(f"…and {len(errors) - 10} more round(s).")
            messagebox.showerror(
                "Input errors",
                "Please correct the following:\n\n" + "\n".join(shown_errors),
                parent=self.root,
            )
            if first_invalid_entry is not None:
                first_invalid_entry.focus_set()
            return

        entropy_bits = "".join(normalized_rounds)
        try:
            result = calculate_bip39(entropy_bits)
        except (ValueError, RuntimeError) as error:
            self._clear_results()
            self.status_var.set("Calculation stopped because an internal check failed.")
            messagebox.showerror("Calculation error", str(error), parent=self.root)
            return

        self._show_results(result)

    def _show_results(self, result: dict[str, object]) -> None:
        groups = result["groups"]
        indices = result["indices"]
        positions = result["positions"]
        words = result["words"]
        final_random = str(result["final_random_bits"])
        checksum = str(result["checksum_bits"])

        self._clear_results()
        self.final_random_var.set(final_random)
        self.checksum_var.set(checksum)
        self.final_group_var.set(final_random + checksum)

        for item_number in range(24):
            source = (
                "11 entropy bits"
                if item_number < 23
                else f"{final_random} + {checksum} checksum"
            )
            self.result_tree.insert(
                "",
                "end",
                values=(
                    item_number + 1,
                    groups[item_number],
                    indices[item_number],
                    positions[item_number],
                    words[item_number],
                    source,
                ),
            )

        self.phrase_text.configure(state="normal")
        self.phrase_text.delete("1.0", "end")
        self.phrase_text.insert("1.0", " ".join(words))
        self.phrase_text.configure(state="disabled")

        self.status_var.set(
            "Success: 256 entropy bits validated, checksum calculated, and 24 words generated."
        )
        self._update_scroll_region()

    def _clear_results(self) -> None:
        for item in self.result_tree.get_children():
            self.result_tree.delete(item)
        self.final_random_var.set("—")
        self.checksum_var.set("—")
        self.final_group_var.set("—")
        self.phrase_text.configure(state="normal")
        self.phrase_text.delete("1.0", "end")
        self.phrase_text.configure(state="disabled")

    def clear_all(self) -> None:
        for entry in self.entries:
            entry.delete(0, "end")
            entry.configure(style="TEntry")
        self._clear_results()
        self.status_var.set("Cleared. Enter all 16 rounds, then calculate.")
        self.canvas.yview_moveto(0)
        self.entries[0].focus_set()


