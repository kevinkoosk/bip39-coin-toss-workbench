def calculate_bip39(entropy_bits: str) -> dict[str, object]:
    """Convert exactly 256 entropy bits into BIP-39 groups and words."""
    if len(BIP39_WORDS) != 2048:
        raise RuntimeError("The embedded BIP-39 word list must contain 2,048 words.")
    if len(entropy_bits) != 256 or set(entropy_bits) - {"0", "1"}:
        raise ValueError("Entropy must contain exactly 256 binary digits.")

    entropy_bytes = int(entropy_bits, 2).to_bytes(32, byteorder="big")
    digest = sha256(entropy_bytes).digest()
    checksum_bits = f"{digest[0]:08b}"
    combined_bits = entropy_bits + checksum_bits

    groups = [
        combined_bits[offset : offset + 11]
        for offset in range(0, 264, 11)
    ]
    indices = [int(group, 2) for group in groups]
    positions = [index + 1 for index in indices]
    words = [BIP39_WORDS[index] for index in indices]

    return {
        "entropy_bits": entropy_bits,
        "final_random_bits": entropy_bits[-3:],
        "checksum_bits": checksum_bits,
        "combined_bits": combined_bits,
        "groups": groups,
        "indices": indices,
        "positions": positions,
        "words": words,
    }


def run_self_test() -> None:
    """Check the implementation against the standard all-zero BIP-39 vector."""
    result = calculate_bip39("0" * 256)
    assert result["checksum_bits"] == "01100110"
    assert result["positions"][-1] == 103
    assert result["words"][-1] == "art"


